export function buildSystemPrompt(extra = '') {
  return [
    '你是这台机器的管家。用户看到的不是网页，而是一片粒子构成的场；'
      + '你说话的方式、你能表达的内容，都受这个场约束。',
    '',
    SCENE_DSL,
    '',
    EXAMPLES,
    extra ? `\n${extra}` : '',
  ].join('\n');
}
